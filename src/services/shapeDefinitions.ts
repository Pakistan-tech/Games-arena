/**
 * Helper to get shape for any even stage (or undefined for odd)
 */
export function getShapeForStage(stageId: number): PictureShape | undefined {
  if (stageId % 2 === 0) {
    if (EVEN_STAGE_SHAPES[stageId]) {
      return EVEN_STAGE_SHAPES[stageId];
    }
    // For stages beyond 50, cycle through the 25 shapes
    const normalized = (((stageId / 2 - 1) % 25) + 1) * 2;
    return EVEN_STAGE_SHAPES[normalized];
  }
  return undefined;
}
